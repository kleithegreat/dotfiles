use super::Target;
use crate::{
    cmd::{GNOME_INTERFACE_DCONF_DIR, dconf_load, dconf_string, run},
    fs_util::{atomic_write, expand_user_path},
    hypr::lua_str,
    theme::schema::{ColorScheme, ThemeState},
};
use std::{fs, io, path::Path};

const OUTPUT_PATH: &str = "~/.local/share/icons/default/index.theme.generated";

pub const TARGET: Target = Target::standalone(
    "cursor",
    &["cursor_theme", "cursor_size"],
    OUTPUT_PATH,
    generate,
)
.comment("#")
.persist(persist)
.on_apply(on_apply);

const HYPR_CURSOR_LUA: &str = "~/.config/hypr/cursor-theme.lua";
const XCURSOR_INDEX: &str = "~/.local/share/icons/default/index.theme";
const LEGACY_XCURSOR_INDEX: &str = "~/.icons/default/index.theme";

fn index_theme_text(cursor_theme: &str) -> String {
    format!("[Icon Theme]\nName=Default\nInherits={cursor_theme}\n")
}

// BreezeX-RosePine-Linux has a separate hyprcursor build (rose-pine-hyprcursor).
fn hyprcursor_theme_for(cursor_theme: &str) -> Option<&'static str> {
    match cursor_theme {
        "BreezeX-RosePine-Linux" => Some("rose-pine-hyprcursor"),
        _ => None,
    }
}

fn replace_with_symlink(
    link_path: &Path,
    target: &Path,
    fallback_contents: &str,
) -> crate::Result<()> {
    if crate::fs_util::replace_with_symlink(link_path, target).is_ok() {
        return Ok(());
    }

    atomic_write(link_path, fallback_contents.as_bytes())
}

pub fn generate(_colors: &ColorScheme, state: &ThemeState) -> crate::Result<String> {
    Ok(index_theme_text(&state.cursor_theme))
}

pub fn persist(_colors: &ColorScheme, state: &ThemeState) -> crate::Result<()> {
    let generated_path = expand_user_path(OUTPUT_PATH)?;
    let xcursor_index = expand_user_path(XCURSOR_INDEX)?;
    let legacy_index = expand_user_path(LEGACY_XCURSOR_INDEX)?;
    let conf_path = expand_user_path(HYPR_CURSOR_LUA)?;

    let mut lines = vec![
        "-- Generated by desktopctl theme -- do not edit".to_owned(),
        "return {".to_owned(),
        format!("    XCURSOR_THEME = {},", lua_str(&state.cursor_theme)),
        format!(
            "    XCURSOR_SIZE = {},",
            lua_str(&state.cursor_size.to_string())
        ),
    ];
    if let Some(hyprcursor_theme) = hyprcursor_theme_for(&state.cursor_theme) {
        lines.push(format!(
            "    HYPRCURSOR_THEME = {},",
            lua_str(hyprcursor_theme)
        ));
    }
    lines.push("}".to_owned());
    atomic_write(&conf_path, format!("{}\n", lines.join("\n")).as_bytes())?;

    for index_path in [xcursor_index, legacy_index] {
        if let Some(parent) = index_path.parent() {
            fs::create_dir_all(parent)?;
        }
        replace_with_symlink(
            &index_path,
            &generated_path,
            &index_theme_text(&state.cursor_theme),
        )?;
    }

    dconf_load(
        GNOME_INTERFACE_DCONF_DIR,
        &[
            ("cursor-theme", dconf_string(&state.cursor_theme)),
            ("cursor-size", state.cursor_size.to_string()),
        ],
    )
}

pub fn on_apply(_colors: &ColorScheme, state: &ThemeState) -> crate::Result<()> {
    // Collect failures so one missing tool does not skip the other updates.
    let mut failures = Vec::new();
    let mut attempt = |result: crate::Result<()>| {
        if let Err(error) = result {
            failures.push(error.to_string());
        }
    };

    let size = state.cursor_size.to_string();
    let hyprcursor_theme = hyprcursor_theme_for(&state.cursor_theme);
    let env = [
        ("XCURSOR_THEME", state.cursor_theme.as_str()),
        ("XCURSOR_SIZE", size.as_str()),
        ("HYPRCURSOR_THEME", hyprcursor_theme.unwrap_or_default()),
    ];
    let hypr_env = env
        .map(|(variable, value)| format!("hl.env({}, {})", lua_str(variable), lua_str(value)))
        .join("\n");
    attempt(crate::hypr::eval(&hypr_env));
    attempt(run([
        "hyprctl",
        "setcursor",
        hyprcursor_theme.unwrap_or(&state.cursor_theme),
        &size,
    ]));
    // `--systemd` also updates the systemd user manager's environment.
    attempt(run([
        "dbus-update-activation-environment".to_owned(),
        "--systemd".to_owned(),
    ]
    .into_iter()
    .chain(env.map(|(variable, value)| format!("{variable}={value}")))));

    if failures.is_empty() {
        Ok(())
    } else {
        Err(io::Error::other(failures.join("; ")).into())
    }
}
